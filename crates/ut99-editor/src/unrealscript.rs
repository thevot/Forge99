/// Active tab in the UnrealScript Class Source & DefaultProperties Studio
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum UcViewerTab {
    Source,
    DefaultProperties,
}

/// An UnrealScript variable declaration with editorial category
#[derive(Debug, Clone, PartialEq)]
pub struct UcVariable {
    pub name: String,
    pub var_type: String,
    pub category: String,
    pub is_editable: bool,
    pub doc: String,
}

/// An UnrealScript function declaration
#[derive(Debug, Clone, PartialEq)]
pub struct UcFunction {
    pub name: String,
    pub return_type: String,
    pub args: String,
    pub is_simulated: bool,
    pub is_final: bool,
    pub is_native: bool,
    pub doc: String,
}

/// Complete deconstructed and metadata representation of an UnrealScript class
#[derive(Debug, Clone, PartialEq)]
pub struct UcClassMetadata {
    pub name: String,
    pub super_class: String,
    pub package: String,
    pub is_abstract: bool,
    pub is_native: bool,
    pub is_noexport: bool,
    pub description: String,
    pub variables: Vec<UcVariable>,
    pub functions: Vec<UcFunction>,
    pub states: Vec<String>,
    pub default_properties: Vec<(String, String)>,
}

impl UcClassMetadata {
    /// Generates canonical, fully-formatted .uc UnrealScript source code
    pub fn to_uc_source(&self) -> String {
        let mut out = String::new();

        // 1. Header Comment
        out.push_str("//=============================================================================\n");
        out.push_str(&format!("// {}.\n", self.name));
        out.push_str(&format!("// Package: {}\n", self.package));
        if !self.description.is_empty() {
            out.push_str(&format!("// Description: {}\n", self.description));
        }
        out.push_str("// Decompiled & generated by Forge99 UnrealScript Studio\n");
        out.push_str("//=============================================================================\n");

        // 2. Class Declaration
        let mut class_line = format!("class {}", self.name);
        if !self.super_class.is_empty() && self.super_class != "None" {
            class_line.push_str(&format!(" extends {}", self.super_class));
        }
        if self.is_abstract {
            class_line.push_str("\n    abstract");
        }
        if self.is_native {
            class_line.push_str("\n    native");
        }
        if self.is_noexport {
            class_line.push_str("\n    noexport");
        }
        class_line.push_str(";\n\n");
        out.push_str(&class_line);

        // 3. Variables by Category
        if !self.variables.is_empty() {
            out.push_str("//-----------------------------------------------------------------------------\n");
            out.push_str("// Properties & Variables\n\n");

            // Group variables by category
            let mut by_cat: HashMap<String, Vec<&UcVariable>> = HashMap::new();
            for v in &self.variables {
                by_cat.entry(v.category.clone()).or_default().push(v);
            }

            let mut sorted_cats: Vec<String> = by_cat.keys().cloned().collect();
            sorted_cats.sort();

            for cat in sorted_cats {
                let vars = &by_cat[&cat];
                if cat.is_empty() {
                    out.push_str("// Internal Variables\n");
                } else {
                    out.push_str(&format!("// {} Properties\n", cat));
                }

                for v in vars {
                    let edit_prefix = if v.is_editable {
                        if v.category.is_empty() {
                            "var() ".to_string()
                        } else {
                            format!("var({}) ", v.category)
                        }
                    } else {
                        "var ".to_string()
                    };

                    out.push_str(&format!("{}{:<18} {};", edit_prefix, v.var_type, v.name));
                    if !v.doc.is_empty() {
                        out.push_str(&format!(" // {}", v.doc));
                    }
                    out.push('\n');
                }
                out.push('\n');
            }
        }

        // 4. Functions & Virtual Events
        if !self.functions.is_empty() {
            out.push_str("//-----------------------------------------------------------------------------\n");
            out.push_str("// Virtual Events & Functions\n\n");

            for f in &self.functions {
                if !f.doc.is_empty() {
                    out.push_str(&format!("// {}\n", f.doc));
                }
                let mut fn_decl = String::new();
                if f.is_native {
                    fn_decl.push_str("native ");
                }
                if f.is_simulated {
                    fn_decl.push_str("simulated ");
                }
                if f.is_final {
                    fn_decl.push_str("final ");
                }

                if f.return_type.is_empty() || f.return_type == "void" {
                    fn_decl.push_str(&format!("function {}({})", f.name, f.args));
                } else if f.name.starts_with("event") {
                    fn_decl.push_str(&format!("event {} {}({})", f.return_type, f.name, f.args));
                } else {
                    fn_decl.push_str(&format!("function {} {}({})", f.return_type, f.name, f.args));
                }

                out.push_str(&fn_decl);
                out.push_str("\n{\n");
                out.push_str(&format!("    // Super.{}({});\n", f.name, f.args.split(',').filter_map(|s| s.trim().split_whitespace().last()).collect::<Vec<_>>().join(", ")));
                out.push_str("}\n\n");
            }
        }

        // 5. States
        if !self.states.is_empty() {
            out.push_str("//-----------------------------------------------------------------------------\n");
            out.push_str("// States\n\n");
            for st in &self.states {
                out.push_str(&format!("state {}\n{{\n    // State implementation\n}}\n\n", st));
            }
        }

        // 6. DefaultProperties Block
        out.push_str("defaultproperties\n{\n");
        for (k, v) in &self.default_properties {
            out.push_str(&format!("    {}={}\n", k, v));
        }
        out.push_str("}\n");

        out
    }
}

/// Retrieves canonical or `.u`-extracted class metadata for any UnrealScript class
pub fn get_class_metadata(class_name: &str, super_name: Option<&str>, package: Option<&str>) -> UcClassMetadata {
    let pkg = package.unwrap_or("Engine").to_string();
    let sup = super_name.unwrap_or("Actor").to_string();

    let mut meta = match class_name {
        "Actor" => build_actor_class(),
        "Light" => build_light_class(),
        "Spotlight" => build_spotlight_class(),
        "TorchFlame" => build_torchflame_class(),
        "ZoneInfo" => build_zone_info_class(),
        "SkyZoneInfo" => build_skyzone_info_class(),
        "WaterZone" => build_waterzone_class(),
        "NavigationPoint" => build_navigation_point_class(),
        "PathNode" => build_pathnode_class(),
        "PlayerStart" => build_playerstart_class(),
        "Teleporter" => build_teleporter_class(),
        "Pawn" => build_pawn_class(),
        "PlayerPawn" => build_player_pawn_class(),
        "TournamentPlayer" => build_tournament_player_class(),
        "Bot" => build_bot_class(),
        "Trigger" => build_trigger_class(),
        "Dispatcher" => build_dispatcher_class(),
        "SpecialEvent" => build_special_event_class(),
        "AmbientSound" => build_ambient_sound_class(),
        "Weapon" => build_weapon_class(),
        "TournamentWeapon" => build_tournament_weapon_class(),
        "ShockRifle" => build_shock_rifle_class(),
        "UT_FlakCannon" => build_flak_cannon_class(),
        "UT_Eightball" => build_eightball_class(),
        "SniperRifle" => build_sniper_rifle_class(),
        "UT_ShieldBelt" => build_shield_belt_class(),
        "UDamage" => build_udamage_class(),
        "Mover" => build_mover_class(),
        _ => build_generic_derived_class(class_name, &sup, &pkg),
    };

    // Attempt to enrich metadata from real .u package ScriptText export if available on disk
    let u_path = std::path::Path::new("UnrealTournament/System").join(format!("{}.u", pkg));
    if u_path.exists() {
        if let Ok(u_pkg) = ut99_format::package::Package::open(&u_path) {
            if let Some(script_text) = ut99_format::package::extract_class_script_text(&u_pkg, class_name) {
                parse_uc_script_into_metadata(&script_text, &mut meta);
            }
        }
    }

    meta
}

/// Parses `var(...)` declarations and `defaultproperties` entries from a raw `.uc` script string into `UcClassMetadata`.
pub fn parse_uc_script_into_metadata(script_text: &str, meta: &mut UcClassMetadata) {
    let mut in_defaults = false;
    for raw_line in script_text.lines() {
        let line = raw_line.trim();
        if line.is_empty() || line.starts_with("//") {
            continue;
        }
        if line.eq_ignore_ascii_case("defaultproperties") {
            in_defaults = true;
            continue;
        }
        if in_defaults {
            if line == "{" {
                continue;
            }
            if line == "}" {
                in_defaults = false;
                continue;
            }
            if let Some((k, v)) = line.split_once('=') {
                let key = k.trim().to_string();
                let val = v.trim().trim_end_matches(';').to_string();
                if let Some(existing) = meta.default_properties.iter_mut().find(|(ek, _)| ek.eq_ignore_ascii_case(&key)) {
                    existing.1 = val;
                } else {
                    meta.default_properties.push((key, val));
                }
            }
        } else if line.to_ascii_lowercase().starts_with("var") {
            let without_semi = line.split(';').next().unwrap_or(line).trim();
            let (cat, rest) = if let Some(open_p) = without_semi.find('(') {
                if let Some(close_p) = without_semi[open_p..].find(')') {
                    let c = without_semi[open_p + 1..open_p + close_p].trim().to_string();
                    let r = without_semi[open_p + close_p + 1..].trim();
                    (Some(c), r)
                } else {
                    (None, without_semi.trim_start_matches("var").trim())
                }
            } else {
                (None, without_semi.trim_start_matches("var").trim())
            };
            let tokens: Vec<&str> = rest.split_whitespace().collect();
            if tokens.len() >= 2 {
                let var_name = tokens.last().copied().unwrap_or("").to_string();
                let var_type = tokens[tokens.len() - 2].to_string();
                if !var_name.is_empty() && !meta.variables.iter().any(|v| v.name.eq_ignore_ascii_case(&var_name)) {
                    meta.variables.push(UcVariable {
                        name: var_name,
                        var_type,
                        category: cat.clone().unwrap_or_default(),
                        is_editable: cat.is_some(),
                        doc: "Extracted from .u ScriptText".into(),
                    });
                }
            }
        }
    }
}

