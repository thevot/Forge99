/// A line-level syntax/compiler diagnostic produced during UnrealScript validation or `ucc make` (`BL-P2-03`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UcCompileDiagnostic {
    pub line: usize,
    pub is_error: bool,
    pub message: String,
}

/// Complete report of an UnrealScript validation and optional `UCC.exe make` invocation (`BL-P2-03`).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct UcCompileReport {
    pub success: bool,
    pub class_name: String,
    pub super_class: String,
    pub diagnostics: Vec<UcCompileDiagnostic>,
    pub ucc_invoked: bool,
    pub log_output: String,
}

/// Validates an UnrealScript `.uc` source buffer for UE1 syntax/semantic rules (`class ... extends/expands ...;`,
/// balanced `{ }`, semicolon-terminated `var` declarations, valid `defaultproperties` `Key=Value` entries)
/// and optionally invokes `UCC.exe make` if `ucc_path` exists on disk (`BL-P2-03`).
pub fn validate_and_compile_uc_source(
    source: &str,
    ucc_path: Option<&std::path::Path>,
) -> UcCompileReport {
    let mut diagnostics = Vec::new();
    let mut class_name = String::new();
    let mut super_class = String::new();
    let mut brace_depth = 0i32;
    let mut in_defaults = false;
    let mut saw_class_decl = false;

    for (idx, raw_line) in source.lines().enumerate() {
        let line_no = idx + 1;
        let code_part = raw_line.split("//").next().unwrap_or(raw_line).trim();
        if code_part.is_empty() {
            continue;
        }

        let lower = code_part.to_ascii_lowercase();
        if !saw_class_decl && lower.starts_with("class ") {
            saw_class_decl = true;
            let tokens: Vec<&str> = code_part
                .trim_end_matches(';')
                .split_whitespace()
                .collect();
            if tokens.len() >= 2 {
                class_name = tokens[1].trim_end_matches(';').to_string();
            } else {
                diagnostics.push(UcCompileDiagnostic {
                    line: line_no,
                    is_error: true,
                    message: "Malformed 'class' declaration: missing class identifier.".to_string(),
                });
            }
            if let Some(ext_pos) = tokens
                .iter()
                .position(|t| t.eq_ignore_ascii_case("extends") || t.eq_ignore_ascii_case("expands"))
            {
                if let Some(&sup) = tokens.get(ext_pos + 1) {
                    super_class = sup.trim_end_matches(';').to_string();
                } else {
                    diagnostics.push(UcCompileDiagnostic {
                        line: line_no,
                        is_error: true,
                        message: "Missing superclass identifier after 'extends'/'expands'."
                            .to_string(),
                    });
                }
            }
        }

        if lower == "defaultproperties" || lower.starts_with("defaultproperties ") {
            in_defaults = true;
        }

        for ch in code_part.chars() {
            if ch == '{' {
                brace_depth += 1;
            } else if ch == '}' {
                brace_depth -= 1;
                if brace_depth <= 0 && in_defaults {
                    in_defaults = false;
                }
                if brace_depth < 0 {
                    diagnostics.push(UcCompileDiagnostic {
                        line: line_no,
                        is_error: true,
                        message: "Unmatched closing brace '}'.".to_string(),
                    });
                    brace_depth = 0;
                }
            }
        }

        if !in_defaults && brace_depth == 0 && (lower.starts_with("var ") || lower.starts_with("var(")) {
            if !code_part.ends_with(';') {
                diagnostics.push(UcCompileDiagnostic {
                    line: line_no,
                    is_error: true,
                    message: "Variable declaration ('var') must end with a semicolon ';'.".to_string(),
                });
            }
        }

        if in_defaults && brace_depth >= 1 && code_part != "{" && code_part != "}" && !lower.starts_with("defaultproperties") {
            if !code_part.contains('=') {
                diagnostics.push(UcCompileDiagnostic {
                    line: line_no,
                    is_error: true,
                    message: format!(
                        "Invalid defaultproperties entry '{}': expected 'PropertyName=Value'.",
                        code_part
                    ),
                });
            } else if code_part.ends_with(';') {
                diagnostics.push(UcCompileDiagnostic {
                    line: line_no,
                    is_error: false,
                    message: "Warning: UE1 defaultproperties entries should not end with ';'.".to_string(),
                });
            }
        }
    }

    if !saw_class_decl {
        diagnostics.push(UcCompileDiagnostic {
            line: 1,
            is_error: true,
            message: "Missing 'class <ClassName> extends <SuperClass>;' declaration.".to_string(),
        });
    }
    if brace_depth != 0 {
        diagnostics.push(UcCompileDiagnostic {
            line: source.lines().count().max(1),
            is_error: true,
            message: format!("Unbalanced braces '{{ }}': {} unclosed block(s).", brace_depth),
        });
    }

    let mut ucc_invoked = false;
    let mut log_output = String::new();

    if !diagnostics.iter().any(|d| d.is_error) {
        if let Some(ucc) = ucc_path {
            if ucc.exists() {
                ucc_invoked = true;
                if let Ok(output) = std::process::Command::new(ucc).arg("make").output() {
                    let stdout = String::from_utf8_lossy(&output.stdout);
                    let stderr = String::from_utf8_lossy(&output.stderr);
                    log_output = format!("{}{}", stdout, stderr);
                    for l in log_output.lines() {
                        let l_low = l.to_ascii_lowercase();
                        if l_low.contains("error,") || l_low.contains("warning,") {
                            let is_err = l_low.contains("error,");
                            let line_num = l
                                .find('(')
                                .and_then(|o| {
                                    l[o + 1..].find(')').and_then(|c| {
                                        l[o + 1..o + 1 + c].trim().parse::<usize>().ok()
                                    })
                                })
                                .unwrap_or(1);
                            diagnostics.push(UcCompileDiagnostic {
                                line: line_num,
                                is_error: is_err,
                                message: l.trim().to_string(),
                            });
                        }
                    }
                }
            }
        }
    }

    let success = !diagnostics.iter().any(|d| d.is_error);
    if log_output.is_empty() {
        if success {
            log_output = format!(
                "UnrealScript Compile OK: class '{}' extends '{}' ({} warning(s)).",
                class_name,
                super_class,
                diagnostics.len()
            );
        } else {
            log_output = format!(
                "UnrealScript Compile FAILED: {} error(s) in '{}'.",
                diagnostics.iter().filter(|d| d.is_error).count(),
                class_name
            );
        }
    }

    UcCompileReport {
        success,
        class_name,
        super_class,
        diagnostics,
        ucc_invoked,
        log_output,
    }
}

