/// Supported interface languages for the UT99 Modern Map Editor (Forge99).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "snake_case")]
pub enum AppLanguage {
    #[default]
    English,
    Italian,
    German,
    French,
    Portuguese,
    Spanish,
    Russian,
    Ukrainian,
    Polish,
    Dutch,
}

impl AppLanguage {
    /// Two-letter ISO 639-1 language code.
    pub fn code(&self) -> &'static str {
        match self {
            Self::English => "en",
            Self::Italian => "it",
            Self::German => "de",
            Self::French => "fr",
            Self::Portuguese => "pt",
            Self::Spanish => "es",
            Self::Russian => "ru",
            Self::Ukrainian => "uk",
            Self::Polish => "pl",
            Self::Dutch => "nl",
        }
    }

    /// Native endonym of the language.
    pub fn native_name(&self) -> &'static str {
        match self {
            Self::English => "English",
            Self::Italian => "Italiano",
            Self::German => "Deutsch",
            Self::French => "Français",
            Self::Portuguese => "Português",
            Self::Spanish => "Español",
            Self::Russian => "Русский",
            Self::Ukrainian => "Українська",
            Self::Polish => "Polski",
            Self::Dutch => "Nederlands",
        }
    }

    /// User-friendly display name with English gloss.
    pub fn display_name(&self) -> &'static str {
        match self {
            Self::English => "English (Default)",
            Self::Italian => "Italiano (Italian)",
            Self::German => "Deutsch (German)",
            Self::French => "Français (French)",
            Self::Portuguese => "Português (Portuguese)",
            Self::Spanish => "Español (Spanish)",
            Self::Russian => "Русский (Russian)",
            Self::Ukrainian => "Українська (Ukrainian)",
            Self::Polish => "Polski (Polish)",
            Self::Dutch => "Nederlands (Dutch)",
        }
    }

    /// Parse from two-letter ISO 639-1 code.
    pub fn from_code(code: &str) -> Option<Self> {
        match code.trim().to_ascii_lowercase().as_str() {
            "en" => Some(Self::English),
            "it" => Some(Self::Italian),
            "de" => Some(Self::German),
            "fr" => Some(Self::French),
            "pt" => Some(Self::Portuguese),
            "es" => Some(Self::Spanish),
            "ru" => Some(Self::Russian),
            "uk" => Some(Self::Ukrainian),
            "pl" => Some(Self::Polish),
            "nl" => Some(Self::Dutch),
            _ => None,
        }
    }

    /// Returns a slice of all available language variants in UI order.
    pub fn all() -> &'static [Self] {
        &[
            Self::English,
            Self::Italian,
            Self::German,
            Self::French,
            Self::Portuguese,
            Self::Spanish,
            Self::Russian,
            Self::Ukrainian,
            Self::Polish,
            Self::Dutch,
        ]
    }
}

// Global runtime override table: (lang_code, key) -> &'static str (leaked string slice for zero-cost lookup)
static RUNTIME_TRANSLATIONS: RwLock<Option<HashMap<(&'static str, &'static str), &'static str>>> =
    RwLock::new(None);

/// Register custom translations from a JSON string at runtime.
/// Format: { "key": "translated value" }
pub fn register_runtime_translations(lang: AppLanguage, json_str: &str) -> Result<usize, String> {
    let parsed: HashMap<String, String> =
        serde_json::from_str(json_str).map_err(|e| format!("Invalid JSON: {e}"))?;
    let count = parsed.len();

    let mut guard = RUNTIME_TRANSLATIONS
        .write()
        .map_err(|_| "Failed to acquire translation write lock".to_string())?;
    let map = guard.get_or_insert_with(HashMap::new);

    let lang_code = lang.code();
    for (k, v) in parsed {
        let leaked_k: &'static str = Box::leak(k.into_boxed_str());
        let leaked_v: &'static str = Box::leak(v.into_boxed_str());
        map.insert((lang_code, leaked_k), leaked_v);
    }

    Ok(count)
}

/// Translates a key according to the active language, strictly falling back to English when untranslated.
pub fn tr<'a>(lang: AppLanguage, key: &'a str) -> &'a str {
    // 1. Check runtime overrides
    if let Ok(guard) = RUNTIME_TRANSLATIONS.read() {
        if let Some(ref map) = *guard {
            if let Some(&val) = map.get(&(lang.code(), key)) {
                return val;
            }
        }
    }

    // 2. Query target language built-in dictionary
    let res = match lang {
        AppLanguage::English => fallback_en(key),
        AppLanguage::Italian => translate_it(key).unwrap_or_else(|| fallback_en(key)),
        AppLanguage::German => translate_de(key).unwrap_or_else(|| fallback_en(key)),
        AppLanguage::French => translate_fr(key).unwrap_or_else(|| fallback_en(key)),
        AppLanguage::Portuguese => translate_pt(key).unwrap_or_else(|| fallback_en(key)),
        AppLanguage::Spanish => translate_es(key).unwrap_or_else(|| fallback_en(key)),
        AppLanguage::Russian => translate_ru(key).unwrap_or_else(|| fallback_en(key)),
        AppLanguage::Ukrainian => translate_uk(key).unwrap_or_else(|| fallback_en(key)),
        AppLanguage::Polish => translate_pl(key).unwrap_or_else(|| fallback_en(key)),
        AppLanguage::Dutch => translate_nl(key).unwrap_or_else(|| fallback_en(key)),
    };

    res
}

