use crate::math::Plane;
use crate::poly::Polygon;
use glam::{Mat4, Vec3};

/// Blend modes for projective texture decals
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ProjectorBlendMode {
    Modulated,   // Multiplicative (bullet holes, shadows)
    Translucent, // Additive (light beams, energy marks)
    Masked,      // 1-bit alpha / cutout (logos, posters)
}

/// A Projector Actor representing a projective texture decal
#[derive(Debug, Clone, PartialEq)]
pub struct Projector {
    pub name: String,
    pub location: Vec3,
    pub rotation: Vec3, // Pitch, Yaw, Roll in degrees
    pub fov: f32,       // 0.0 for Orthogonal, > 0.0 for Perspective FOV in degrees
    pub width: f32,     // Orthogonal width or base scale
    pub height: f32,    // Orthogonal height or base scale
    pub max_trace_distance: f32,
    pub texture: String,
    pub blend_mode: ProjectorBlendMode,
    pub project_bsp: bool,
    pub project_static_mesh: bool,
}

impl Default for Projector {
    fn default() -> Self {
        Self {
            name: "Projector0".to_string(),
            location: Vec3::ZERO,
            rotation: Vec3::new(0.0, 0.0, 0.0), // Direction along +X by default
            fov: 0.0,                            // Ortho by default (cleanest for wall decals)
            width: 128.0,
            height: 128.0,
            max_trace_distance: 512.0,
            texture: "Botpack.BloodSplat".to_string(),
            blend_mode: ProjectorBlendMode::Modulated,
            project_bsp: true,
            project_static_mesh: true,
        }
    }
}

/// A clipped and UV-mapped decal polygon fragment generated by a Projector
#[derive(Debug, Clone, PartialEq)]
pub struct ProjectedDecalPoly {
    pub vertices: Vec<Vec3>,
    pub uvs: Vec<[f32; 2]>,
    pub normal: Vec3,
    pub texture: String,
    pub blend_mode: ProjectorBlendMode,
}

impl Projector {
    /// Computes the orientation vectors (Forward, Right, Up) from Pitch, Yaw, Roll (degrees)
    pub fn get_axes(&self) -> (Vec3, Vec3, Vec3) {
        let rad_pitch = self.rotation.x.to_radians();
        let rad_yaw = self.rotation.y.to_radians();
        let rad_roll = self.rotation.z.to_radians();

        let rot = Mat4::from_euler(glam::EulerRot::YXZ, rad_yaw, rad_pitch, rad_roll);
        let forward = rot.transform_vector3(Vec3::X).normalize();
        let right = rot.transform_vector3(Vec3::Y).normalize();
        let up = rot.transform_vector3(Vec3::Z).normalize();
        (forward, right, up)
    }

    /// Creates an ortho projector placed in front of a hit surface and oriented to project directly onto it.
    pub fn from_surface_hit(
        hit_pos: Vec3,
        surface_normal: Vec3,
        width: f32,
        height: f32,
        texture: String,
        blend_mode: ProjectorBlendMode,
    ) -> Self {
        let n = surface_normal.normalize();
        let target_fwd = -n;

        let guide = if target_fwd.z.abs() < 0.9 {
            Vec3::Z
        } else {
            Vec3::Y
        };
        let right = guide.cross(target_fwd).normalize();
        let up = target_fwd.cross(right).normalize();

        let mat = glam::Mat3::from_cols(target_fwd, right, up);
        let quat = glam::Quat::from_mat3(&mat);
        let (yaw, pitch, roll) = quat.to_euler(glam::EulerRot::YXZ);

        Self {
            name: "DecalProjector".to_string(),
            location: hit_pos + n * 8.0,
            rotation: Vec3::new(pitch.to_degrees(), yaw.to_degrees(), roll.to_degrees()),
            fov: 0.0,
            width,
            height,
            max_trace_distance: 64.0,
            texture,
            blend_mode,
            project_bsp: true,
            project_static_mesh: true,
        }
    }

    /// Generates the 6 bounding clipping planes for the projection volume.
    /// Plane normals point INSIDE the projection volume.
    pub fn get_frustum_planes(&self) -> Vec<Plane> {
        let (fwd, right, up) = self.get_axes();
        let mut planes = Vec::with_capacity(6);

        // Near plane: at location, normal points forward
        planes.push(Plane {
            normal: fwd,
            dist: fwd.dot(self.location),
        });

        // Far plane: at location + fwd * max_trace_distance, normal points backward (-fwd)
        let far_pt = self.location + fwd * self.max_trace_distance;
        planes.push(Plane {
            normal: -fwd,
            dist: (-fwd).dot(far_pt),
        });

        let hw = self.width * 0.5;
        let hh = self.height * 0.5;

        if self.fov <= 0.0 {
            // Orthogonal Frustum / Box
            // Right plane (positive right, normal points inward = -right)
            let r_pos = self.location + right * hw;
            planes.push(Plane {
                normal: -right,
                dist: (-right).dot(r_pos),
            });

            // Left plane (negative right, normal points inward = +right)
            let l_pos = self.location - right * hw;
            planes.push(Plane {
                normal: right,
                dist: right.dot(l_pos),
            });

            // Top plane (positive up, normal points inward = -up)
            let t_pos = self.location + up * hh;
            planes.push(Plane {
                normal: -up,
                dist: (-up).dot(t_pos),
            });

            // Bottom plane (negative up, normal points inward = +up)
            let b_pos = self.location - up * hh;
            planes.push(Plane {
                normal: up,
                dist: up.dot(b_pos),
            });
        } else {
            // Perspective Frustum
            let half_fov_rad = (self.fov * 0.5).to_radians();
            let cos_fov = half_fov_rad.cos();
            let sin_fov = half_fov_rad.sin();

            // Right plane normal
            let r_norm = (fwd * sin_fov - right * cos_fov).normalize();
            planes.push(Plane {
                normal: r_norm,
                dist: r_norm.dot(self.location),
            });

            // Left plane normal
            let l_norm = (fwd * sin_fov + right * cos_fov).normalize();
            planes.push(Plane {
                normal: l_norm,
                dist: l_norm.dot(self.location),
            });

            // Top plane normal
            let t_norm = (fwd * sin_fov - up * cos_fov).normalize();
            planes.push(Plane {
                normal: t_norm,
                dist: t_norm.dot(self.location),
            });

            // Bottom plane normal
            let b_norm = (fwd * sin_fov + up * cos_fov).normalize();
            planes.push(Plane {
                normal: b_norm,
                dist: b_norm.dot(self.location),
            });
        }

        planes
    }

    /// Projects this decal onto a list of candidate world polygons.
    /// Applies Sutherland-Hodgman clipping, backface culling, UV calculation,
    /// and normal offset (+0.15 units) to eliminate Z-fighting.
    pub fn project_onto_polygons(&self, world_polys: &[Polygon]) -> Vec<ProjectedDecalPoly> {
        let (fwd, right, up) = self.get_axes();
        let planes = self.get_frustum_planes();
        let mut decal_polys = Vec::new();

        let half_fov_tan = (self.fov * 0.5).to_radians().tan();

        for poly in world_polys {
            if poly.vertices.len() < 3 {
                continue;
            }

            // 1. Backface check against projector direction
            // Decal only applies to surfaces that face towards the projector
            if poly.plane.normal.dot(fwd) >= -0.05 {
                continue;
            }

            // 2. Clip polygon against the 6 frustum planes
            let mut current_verts = poly.vertices.clone();

            for plane in &planes {
                current_verts = clip_polygon_against_plane(&current_verts, plane);
                if current_verts.len() < 3 {
                    break;
                }
            }

            if current_verts.len() < 3 {
                continue;
            }

            // 3. Compute Decal UV coordinates
            let mut uvs = Vec::with_capacity(current_verts.len());
            let mut offset_verts = Vec::with_capacity(current_verts.len());

            for &v in &current_verts {
                let rel = v - self.location;

                let (u, v_coord) = if self.fov <= 0.0 {
                    // Ortho projection
                    let u = rel.dot(right) / self.width + 0.5;
                    let v = 0.5 - rel.dot(up) / self.height;
                    (u, v)
                } else {
                    // Perspective projection
                    let dist_fwd = rel.dot(fwd).max(1.0);
                    let scale = 2.0 * dist_fwd * half_fov_tan;
                    let u = rel.dot(right) / scale + 0.5;
                    let v = 0.5 - rel.dot(up) / scale;
                    (u, v)
                };

                uvs.push([u, v_coord]);

                // Offset vertex slightly along surface normal to prevent Z-fighting
                offset_verts.push(v + poly.plane.normal * 0.15);
            }

            decal_polys.push(ProjectedDecalPoly {
                vertices: offset_verts,
                uvs,
                normal: poly.plane.normal,
                texture: self.texture.clone(),
                blend_mode: self.blend_mode,
            });
        }

        decal_polys
    }
}

/// Sutherland-Hodgman polygon clipping against a half-space plane.
/// Points with plane.dot(p) >= plane.dist are INSIDE the frustum.
fn clip_polygon_against_plane(verts: &[Vec3], plane: &Plane) -> Vec<Vec3> {
    if verts.len() < 3 {
        return Vec::new();
    }

    let mut output = Vec::with_capacity(verts.len());
    let mut prev_pt = *verts.last().unwrap();
    let mut prev_dist = plane.normal.dot(prev_pt) - plane.dist;

    for &curr_pt in verts {
        let curr_dist = plane.normal.dot(curr_pt) - plane.dist;

        if curr_dist >= -1e-4 {
            if prev_dist < -1e-4 {
                // Entering plane: calculate intersection
                let t = prev_dist / (prev_dist - curr_dist);
                output.push(prev_pt + (curr_pt - prev_pt) * t);
            }
            output.push(curr_pt);
        } else if prev_dist >= -1e-4 {
            // Exiting plane: calculate intersection
            let t = prev_dist / (prev_dist - curr_dist);
            output.push(prev_pt + (curr_pt - prev_pt) * t);
        }

        prev_pt = curr_pt;
        prev_dist = curr_dist;
    }

    output
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::poly::Polygon;

    #[test]
    fn test_projector_ortho_projection_onto_wall() {
        // Wall at X = 200 facing -X (normal = -Vec3::X)
        let wall = Polygon::new(vec![
            Vec3::new(200.0,  100.0, -100.0),
            Vec3::new(200.0, -100.0, -100.0),
            Vec3::new(200.0, -100.0,  100.0),
            Vec3::new(200.0,  100.0,  100.0),
        ]).unwrap();

        // Projector at X = 0 pointing towards +X (yaw = 0, pitch = 0, roll = 0)
        let mut proj = Projector::default();
        proj.location = Vec3::new(0.0, 0.0, 0.0);
        proj.rotation = Vec3::ZERO;
        proj.width = 64.0;
        proj.height = 64.0;
        proj.max_trace_distance = 500.0;
        proj.texture = "Botpack.BloodSplat".to_string();

        let decals = proj.project_onto_polygons(&[wall]);
        assert_eq!(decals.len(), 1, "Should generate exactly 1 decal fragment on the wall");

        let decal = &decals[0];
        assert_eq!(decal.vertices.len(), 4, "Decal clipped against 64x64 bounds should be a quad");
        assert_eq!(decal.texture, "Botpack.BloodSplat");

        // Verify UVs are within [0, 1] range
        for uv in &decal.uvs {
            assert!(uv[0] >= -1e-3 && uv[0] <= 1.0 + 1e-3, "U coordinate must be in [0, 1]");
            assert!(uv[1] >= -1e-3 && uv[1] <= 1.0 + 1e-3, "V coordinate must be in [0, 1]");
        }

        // Verify slight offset along normal to prevent Z-fighting (-X normal -> x = 200 - 0.15)
        for v in &decal.vertices {
            assert!((v.x - (200.0 - 0.15)).abs() < 1e-3, "Vertex must be offset along normal");
        }
    }

    #[test]
    fn test_projector_backface_culling() {
        // Wall at X = 200 facing +X (normal = +Vec3::X, away from projector)
        let wall = Polygon::new(vec![
            Vec3::new(200.0, -100.0, -100.0),
            Vec3::new(200.0,  100.0, -100.0),
            Vec3::new(200.0,  100.0,  100.0),
            Vec3::new(200.0, -100.0,  100.0),
        ]).unwrap();

        let proj = Projector::default();
        let decals = proj.project_onto_polygons(&[wall]);
        assert_eq!(decals.len(), 0, "Backfacing surfaces must not receive decals");
    }

    #[test]
    fn test_projector_distance_culling() {
        // Wall at X = 1000, but projector max trace distance is 512
        let wall = Polygon::new(vec![
            Vec3::new(1000.0, -100.0, -100.0),
            Vec3::new(1000.0,  100.0, -100.0),
            Vec3::new(1000.0,  100.0,  100.0),
            Vec3::new(1000.0, -100.0,  100.0),
        ]).unwrap();

        let mut proj = Projector::default();
        proj.max_trace_distance = 512.0;
        let decals = proj.project_onto_polygons(&[wall]);
        assert_eq!(decals.len(), 0, "Surfaces beyond max trace distance must not receive decals");
    }

    #[test]
    fn test_projector_from_surface_hit() {
        let directions = [
            (Vec3::new( 1.0,  0.0,  0.0), Vec3::new( 100.0, 0.0, 0.0)),
            (Vec3::new(-1.0,  0.0,  0.0), Vec3::new(-100.0, 0.0, 0.0)),
            (Vec3::new( 0.0,  1.0,  0.0), Vec3::new(0.0,  100.0, 0.0)),
            (Vec3::new( 0.0, -1.0,  0.0), Vec3::new(0.0, -100.0, 0.0)),
            (Vec3::new( 0.0,  0.0,  1.0), Vec3::new(0.0, 0.0,  100.0)),
            (Vec3::new( 0.0,  0.0, -1.0), Vec3::new(0.0, 0.0, -100.0)),
        ];

        for (normal, hit_pos) in directions {
            // Build a square polygon centered at hit_pos with given normal
            let guide = if normal.z.abs() < 0.9 { Vec3::Z } else { Vec3::Y };
            let tangent = guide.cross(normal).normalize();
            let bitangent = normal.cross(tangent).normalize();
            let half_sz = 150.0;

            let poly = Polygon::new(vec![
                hit_pos - tangent * half_sz - bitangent * half_sz,
                hit_pos + tangent * half_sz - bitangent * half_sz,
                hit_pos + tangent * half_sz + bitangent * half_sz,
                hit_pos - tangent * half_sz + bitangent * half_sz,
            ]).unwrap();

            let proj = Projector::from_surface_hit(
                hit_pos,
                normal,
                64.0,
                64.0,
                "Botpack.BloodSplat".to_string(),
                ProjectorBlendMode::Modulated,
            );

            let (fwd, _, _) = proj.get_axes();
            assert!(fwd.dot(-normal) > 0.99, "Projector forward must align with -normal for normal {}", normal);

            let decals = proj.project_onto_polygons(&[poly]);
            assert_eq!(decals.len(), 1, "Must generate decal fragment for surface with normal {}", normal);
            assert_eq!(decals[0].vertices.len(), 4, "Decal should be a quad for normal {}", normal);
        }
    }
}
